export function getDomainsBySection(id: SectionId): Domain[] {
  return domains.filter((domain) => domain.sectionId === id);
}

export function getDomain(id: DomainId): Domain {
  return domains.find((domain) => domain.id === id)!;
}

const skillIndex = new Map(domains.flatMap((domain) => domain.skills.map((skill) => [skill.id, skill] as const)));

export function getSkill(id: string): Skill | undefined {
  return skillIndex.get(id);
}

